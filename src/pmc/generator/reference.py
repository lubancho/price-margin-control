def _build_products() -> list[Product]:
    names_by_category: dict[int, list[str]] = {
        1: [f"Ролл {b}" for b in _ROLL_BASES] + [f"Ролл {b} запечённый" for b in _ROLL_BASES],
        2: [f"Суши нигири {f}" for f in _SUSHI_FISH] + [f"Гункан {f}" for f in _SUSHI_FISH],
        3: [f"Набор «{n}»" for n in _SET_NAMES],
        4: list(_DRINKS),
        5: list(_SNACKS),
    }
    products: list[Product] = []
    pid = 1
    for cat in CATEGORIES:
        for n, name in enumerate(names_by_category[cat.category_id], start=1):
            products.append(
                Product(
                    product_id=pid,
                    sku=f"{cat.sku_prefix}-{n:04d}",
                    name=name,
                    category_id=cat.category_id,
                    sale_unit=cat.sale_unit,
                    is_fresh=cat.is_fresh,
                )
            )
            pid += 1
    return products


PRODUCTS: list[Product] = _build_products()

